#!/usr/bin/env bash
# setup-hysteria-node.sh
# Configures Hysteria2 sidecar for a Marzban-node instance.
# Run once per node, then: docker compose --profile hysteria2 up -d
#
# Prerequisites:
#   - HYSTERIA2_MARZBAN_URL  — public HTTPS URL of the MAIN Marzban panel
#                              (e.g. https://marzban.example.com or https://1.2.3.4:443)
#   - HYSTERIA2_HOOK_TOKEN   — value of HYSTERIA2_HOOK_TOKEN from main Marzban .env
#
# Both can be passed as env vars or answered interactively.

set -euo pipefail

NODE_DIR="${NODE_DIR:-/var/lib/marzban-node}"
ENV_FILE="${ENV_FILE:-/opt/marzban-node/.env}"
HYSTERIA_YAML="${NODE_DIR}/hysteria.yaml"

# ── helpers ──────────────────────────────────────────────────────────────────

log()  { echo "[setup-hysteria-node] $*"; }
err()  { echo "[setup-hysteria-node] ERROR: $*" >&2; exit 1; }

env_get() {
    local key="$1" default="${2:-}"
    if [ -f "$ENV_FILE" ]; then
        local val
        val=$(grep -E "^${key}\s*=" "$ENV_FILE" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d '"' | tr -d "'" | xargs)
        echo "${val:-$default}"
    else
        echo "$default"
    fi
}

env_set() {
    local key="$1" value="$2"
    mkdir -p "$(dirname "$ENV_FILE")"
    touch "$ENV_FILE"
    if grep -qE "^${key}\s*=" "$ENV_FILE" 2>/dev/null; then
        # Replace existing key (portable sed -i)
        sed -i "s|^${key}\s*=.*|${key} = ${value}|" "$ENV_FILE"
    else
        echo "${key} = ${value}" >> "$ENV_FILE"
    fi
}

generate_secret() {
    python3 -c "import secrets; print(secrets.token_urlsafe(32))" 2>/dev/null \
        || openssl rand -base64 32 | tr -dc 'a-zA-Z0-9_-' | head -c 32 \
        || cat /dev/urandom | tr -dc 'a-zA-Z0-9' | fold -w 32 | head -n 1
}

# ── resolve required values ───────────────────────────────────────────────────

MARZBAN_URL="${HYSTERIA2_MARZBAN_URL:-$(env_get HYSTERIA2_MARZBAN_URL)}"
if [ -z "$MARZBAN_URL" ]; then
    read -rp "Main Marzban panel URL (e.g. https://panel.example.com): " MARZBAN_URL
fi
MARZBAN_URL="${MARZBAN_URL%/}"   # strip trailing slash
[ -z "$MARZBAN_URL" ] && err "HYSTERIA2_MARZBAN_URL is required"

HOOK_TOKEN="${HYSTERIA2_HOOK_TOKEN:-$(env_get HYSTERIA2_HOOK_TOKEN)}"
if [ -z "$HOOK_TOKEN" ]; then
    read -rp "HYSTERIA2_HOOK_TOKEN from main Marzban .env: " HOOK_TOKEN
fi
[ -z "$HOOK_TOKEN" ] && err "HYSTERIA2_HOOK_TOKEN is required"

HYSTERIA_PORT="${HYSTERIA2_PORT:-$(env_get HYSTERIA2_PORT 2083)}"

CERT_FILE="${HYSTERIA2_CERT_FILE:-$(env_get HYSTERIA2_CERT_FILE "${NODE_DIR}/ssl_cert.pem")}"
KEY_FILE="${HYSTERIA2_KEY_FILE:-$(env_get HYSTERIA2_KEY_FILE "${NODE_DIR}/ssl_key.pem")}"

# Generate traffic secret if not set
TRAFFIC_SECRET="$(env_get HYSTERIA2_TRAFFIC_SECRET)"
if [ -z "$TRAFFIC_SECRET" ]; then
    TRAFFIC_SECRET="$(generate_secret)"
    log "Generated HYSTERIA2_TRAFFIC_SECRET"
fi

TRAFFIC_LISTEN="$(env_get HYSTERIA2_TRAFFIC_LISTEN "127.0.0.1:9999")"

UP_MBPS="$(env_get HYSTERIA2_UP_MBPS 500)"
DOWN_MBPS="$(env_get HYSTERIA2_DOWN_MBPS 500)"

# ── write .env ────────────────────────────────────────────────────────────────

log "Updating ${ENV_FILE}..."
env_set HYSTERIA2_ENABLED       true
env_set HYSTERIA2_PORT          "$HYSTERIA_PORT"
env_set HYSTERIA2_MARZBAN_URL   "$MARZBAN_URL"
env_set HYSTERIA2_HOOK_TOKEN    "$HOOK_TOKEN"
env_set HYSTERIA2_TRAFFIC_SECRET "$TRAFFIC_SECRET"
env_set HYSTERIA2_TRAFFIC_LISTEN "$TRAFFIC_LISTEN"
env_set HYSTERIA2_UP_MBPS       "$UP_MBPS"
env_set HYSTERIA2_DOWN_MBPS     "$DOWN_MBPS"
env_set HYSTERIA2_CERT_FILE     "$CERT_FILE"
env_set HYSTERIA2_KEY_FILE      "$KEY_FILE"

# Enable the Docker Compose profile automatically
env_set COMPOSE_PROFILES        hysteria2

# ── write hysteria.yaml ───────────────────────────────────────────────────────

mkdir -p "$NODE_DIR"

if [ -f "$HYSTERIA_YAML" ]; then
    cp "$HYSTERIA_YAML" "${HYSTERIA_YAML}.bak"
    log "Backed up existing hysteria.yaml → hysteria.yaml.bak"
fi

log "Writing ${HYSTERIA_YAML}..."

cat > "$HYSTERIA_YAML" << YAML
# hysteria.yaml — auto-generated by setup-hysteria-node.sh
# Regenerate by running: bash /opt/marzban-node/setup-hysteria-node.sh

listen: ":${HYSTERIA_PORT}"

tls:
  cert: /var/lib/marzban-node/ssl_cert.pem
  key:  /var/lib/marzban-node/ssl_key.pem

auth:
  type: http
  http:
    url: ${MARZBAN_URL}/api/hysteria/auth?token=${HOOK_TOKEN}
    # insecure: skip TLS verification for main Marzban panel (needed if panel uses self-signed cert)
    insecure: true

bandwidth:
  up:   ${UP_MBPS} mbps
  down: ${DOWN_MBPS} mbps

trafficStats:
  listen: ${TRAFFIC_LISTEN}
  secret: ${TRAFFIC_SECRET}

masquerade:
  type: proxy
  proxy:
    url: https://news.ycombinator.com
    rewriteHost: true
YAML

log "hysteria.yaml written."

# ── verify cert files exist ───────────────────────────────────────────────────

if [ ! -f "${NODE_DIR}/ssl_cert.pem" ]; then
    log "WARNING: ${NODE_DIR}/ssl_cert.pem not found."
    log "  Start marzban-node once first so it generates the cert, then re-run this script."
fi

# ── done ─────────────────────────────────────────────────────────────────────

log ""
log "Done! To start hysteria2 alongside the node:"
log "  cd /opt/marzban-node && docker compose --profile hysteria2 up -d"
log ""
log "Or simply: docker compose up -d   (COMPOSE_PROFILES=hysteria2 is now set in .env)"
log ""
log "Verify auth is working after startup:"
log "  curl -s -X POST '${MARZBAN_URL}/api/hysteria/auth?token=${HOOK_TOKEN}' \\"
log "       -H 'Content-Type: application/json' \\"
log "       -d '{\"addr\":\"127.0.0.1:1234\",\"auth\":\"test_password\",\"id\":\"test\"}'"
